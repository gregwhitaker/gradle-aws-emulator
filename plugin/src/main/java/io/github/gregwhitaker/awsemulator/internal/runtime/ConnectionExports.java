package io.github.gregwhitaker.awsemulator.internal.runtime;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.stream.Collectors;

/** Sourceable scripts containing paths and connection settings, never credential values. */
public final class ConnectionExports {
    private ConnectionExports() {}

    public static void write(EmulatorConnection connection, Path home) throws IOException {
        String names = EmulatorConnection.CREDENTIAL_ENVIRONMENT.stream().sorted().collect(Collectors.joining("|"));
        StringBuilder shell = new StringBuilder("# Generated by exportAwsEmulatorConnection. Source in your development shell.\n")
            .append("# Regenerate after restarting the emulator. Close this shell to discard its environment.\n")
            .append("for _aws_emulator_name in $(env | sed -n 's/^\\([A-Za-z_][A-Za-z0-9_]*\\)=.*/\\1/p'); do\n")
            .append("  case \"$_aws_emulator_name\" in\n    ").append(names)
            .append("|AWS_CONTAINER_CREDENTIALS_*|AWS_CONTAINER_AUTHORIZATION_*|AWS_ENDPOINT_URL*) unset \"$_aws_emulator_name\" ;;\n")
            .append("  esac\ndone\nunset _aws_emulator_name\n");
        StringBuilder powershell = new StringBuilder("# Generated by exportAwsEmulatorConnection. Dot-source in your development shell.\n")
            .append("# Regenerate after restarting the emulator. Close this shell to discard its environment.\n")
            .append("Get-ChildItem Env: | Where-Object { $_.Name -match '^(?:").append(names)
            .append("|AWS_CONTAINER_CREDENTIALS_.*|AWS_CONTAINER_AUTHORIZATION_.*|AWS_ENDPOINT_URL.*)$' } | ForEach-Object {\n")
            .append("    Remove-Item -LiteralPath ('Env:' + $_.Name)\n}\n");
        connection.connectionEnvironment().forEach((name, value) -> {
            shell.append("export ").append(name).append("='").append(value.toString().replace("'", "'\"'\"'")).append("'\n");
            powershell.append("$env:").append(name).append(" = '").append(value.toString().replace("'", "''")).append("'\n");
        });
        writePrivate(home.resolve("connection.sh"), shell.toString());
        writePrivate(home.resolve("connection.ps1"), powershell.toString());
    }

    private static void writePrivate(Path file, String content) throws IOException {
        Files.writeString(file, content);
        if (Files.getFileStore(file).supportsFileAttributeView("posix")) {
            Files.setPosixFilePermissions(file, PosixFilePermissions.fromString("rw-------"));
        }
    }
}
